use anyhow::Result;
use console::style;
use dsp_core::signal::{LabelVocabulary, SignalFamily};
use dsp_io::config::StorageConfig;
use dsp_io::recording_meta::{RecordingMeta, TrackMeta};
use dsp_io::zarr::StorageManager;
use std::path::PathBuf;

fn main() -> Result<()> {
    println!(
        "LAB_15  {}",
        style("Spike Artifact Storage Verification").bold().cyan()
    );

    let zarr_path = PathBuf::from("data/lab15/spike_test.zarr");
    if zarr_path.exists() {
        std::fs::remove_dir_all(&zarr_path)?;
    }

    let config = StorageConfig {
        sample_rate: 40_000,
        channels: 4,
        chunk_size: 32768,
        raw_archive_path: zarr_path.clone(),
        ..Default::default()
    };

    let manager = StorageManager::new(config.clone())?;

    // 1. Initialize recording with dummy metadata
    let mut meta = RecordingMeta {
        session_id: "lab15".into(),
        recording_name: "Spike Storage Test".into(),
        recording_type: "test".into(),
        description: "Generated by lab_15".into(),
        sample_rate: 40_000.0,
        n_channels: 4,
        total_samples: 40_000 * 10, // 10 seconds
        channel_names: (0..4).map(|i| format!("CH{}", i)).collect(),
        lod_levels_available: vec![0],
        created_at: "".into(),
        virtual_channels: vec![],
        tracks: vec![],
        preferred_blueprint: None,
        annotations: vec![],
    };

    let track_name = "sorted_spikes";
    meta.tracks.push(TrackMeta {
        name: track_name.into(),
        channel_indices: vec![0, 1, 2, 3],
        family: SignalFamily::events(),
        label_vocabulary: LabelVocabulary::new(vec![
            "Noise".into(),
            "Unit A".into(),
            "Unit B".into(),
        ]),
    });

    manager.init_hierarchy(&dsp_io::metadata::DatasetMetadata::new_power_of_two(
        meta.total_samples,
    ))?;
    meta.save(&zarr_path)?;

    // 2. Generate Mock Spikes
    let n_spikes = 1000;
    let snippet_len = 48;
    let n_pcs = 3;

    let mut offsets = Vec::with_capacity(n_spikes);
    let mut labels = Vec::with_capacity(n_spikes);
    let mut waveforms = Vec::with_capacity(n_spikes * snippet_len);
    let mut pca_features = Vec::with_capacity(n_spikes * n_pcs);

    let mut seed = 42u32;
    let mut pseudo_rand = || {
        seed = seed.wrapping_mul(1103515245).wrapping_add(12345);
        ((seed >> 16) & 0x7FFF) as f32 / 32768.0
    };

    for i in 0..n_spikes {
        offsets.push(i as u64 * 400); // 10ms spacing
        let label = (i % 2) + 1; // Alternating Unit A and Unit B
        labels.push(label as u32);

        // Unit A (Label 1) has a deep trough, Unit B (Label 2) has a sharp peak
        for t in 0..snippet_len {
            let val = if label == 1 {
                -5.0 * (-(t as f32 - 20.0).powi(2) / 20.0).exp()
            } else {
                3.0 * (-(t as f32 - 24.0).powi(2) / 10.0).exp()
            };
            waveforms.push(val + (pseudo_rand() * 0.5)); // add noise
        }

        // Separate clusters in PCA space
        if label == 1 {
            pca_features.push(-2.0 + (pseudo_rand() * 0.5)); // PC1
            pca_features.push(1.0 + (pseudo_rand() * 0.5)); // PC2
            pca_features.push(0.0); // PC3
        } else {
            pca_features.push(2.0 + (pseudo_rand() * 0.5));
            pca_features.push(-1.0 + (pseudo_rand() * 0.5));
            pca_features.push(0.0);
        }
    }

    println!("Saving {} spikes to track '{}'...", n_spikes, track_name);

    manager.write_spike_artifacts(
        track_name,
        &offsets,
        &labels,
        &waveforms,
        &pca_features,
        n_spikes,
        snippet_len,
        n_pcs,
    )?;

    println!(
        "{}",
        style("Verification data generated successfully.")
            .green()
            .bold()
    );

    // 3. Verify Readback
    println!("\nVerifying Readback...");
    if !manager.has_flat_artifacts(track_name) {
        return Err(anyhow::anyhow!("Flat artifacts not found after writing!"));
    }

    let unit_a_indices = manager.read_flat_indices_for_label(track_name, 1)?;
    println!(
        "  Found {} spikes for Unit A (Label 1)",
        unit_a_indices.len()
    );
    assert_eq!(unit_a_indices.len(), 500);

    let subset_indices = vec![unit_a_indices[0], unit_a_indices[10]];
    let (read_waveforms, read_pca) =
        manager.read_spike_artifacts_subset(track_name, &subset_indices, snippet_len, n_pcs)?;

    println!(
        "  Read {} waveforms and {} PCA features",
        read_waveforms.len() / snippet_len,
        read_pca.len() / n_pcs
    );
    assert_eq!(read_waveforms.len(), 2 * snippet_len);
    assert_eq!(read_pca.len(), 2 * n_pcs);

    println!("{}", style("Readback verification PASSED.").green().bold());
    println!("Zarr path: {}", zarr_path.display());

    Ok(())
}
